def clean(raw: str) -> str:
    """Strip metadata headers, badges, and markup so only prose is scored."""
    body = raw.split("\n\n", 1)[-1]
    body = re.sub(r"!?\[[^\]]*\]\([^)]*\)", " ", body)      # markdown links/images
    body = re.sub(r"^\s*[|+:.-]{2,}.*$", " ", body, flags=re.M)  # tables, rules
    body = re.sub(r"^\s*(?:[-*=~^]{3,}|\.\. .*|\s{4,}\S.*)$", " ", body, flags=re.M)
    body = re.sub(r"[`*_#>]+", " ", body)
    body = re.sub(r"https?://\S+", " ", body)
    body = re.sub(r"[ \t]+", " ", body)
    prose = [line.strip() for line in body.splitlines() if len(line.strip()) > 40]
    return "\n".join(prose)[:4000]


def load_samples() -> list[tuple[str, str, str]]:
    samples = []
    for name, relative in HUMAN_SOURCES:
        path = SITE_PACKAGES / relative
        if not path.is_file():
            print(f"  (skipping {name}: {path} not installed)")
            continue
        text = clean(path.read_text(errors="replace"))
        if len(text) > 500:
            samples.append(("human", name, text))
    for name, text in MACHINE_SAMPLES:
        samples.append(("machine", name, " ".join(text.split())))
    return samples


def main() -> int:
    samples = load_samples()
    humans = [s for s in samples if s[0] == "human"]
    machines = [s for s in samples if s[0] == "machine"]
    print(f"{len(humans)} known-human and {len(machines)} known-machine samples\n")

    device, _ = select_runtime_device()
    loader = TransformersLoader(read_hf_token())
    verdicts = {}

    for model in TEXT_MODELS:
        predict = loader.load_text(model, device)
        print(f"{model.name} ({model.model_id})")
        means = {}
        for truth in ("human", "machine"):
            scores = [
                predict(text[: model.max_characters])["ai"]
                for label, _, text in samples
                if label == truth
            ]
            means[truth] = sum(scores) / len(scores)
            for (label, name, _), score in zip(
                [s for s in samples if s[0] == truth], scores
            ):
                print(f"  {truth:8} {name:16} score={score:.4f}")
        gap = means["machine"] - means["human"]
        verdicts[model.name] = gap
        print(
            f"  mean(human)={means['human']:.4f}  mean(machine)={means['machine']:.4f}"
            f"  gap={gap:+.4f}\n"
        )
        loader.release()

    print("=" * 60)
    for name, gap in verdicts.items():
        if gap > 0.2:
            print(f"{name}: polarity CORRECT (machine scores higher by {gap:+.3f})")
        elif gap < -0.2:
            print(f"{name}: polarity INVERTED (machine scores lower by {gap:+.3f})")
        else:
            print(f"{name}: INCONCLUSIVE (gap {gap:+.3f} — the model is not separating)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
