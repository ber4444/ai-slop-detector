"""Settle detector polarity against text whose authorship is known.

This is an opt-in diagnostic, not part of the test suite: it downloads and runs
the real models. It answers one question — does a high score actually mean
"machine written" for each detector, or is the polarity inverted?

Ground truth:
  human — prose shipped in packages released years before consumer LLMs.
  machine — text generated by a language model for this probe.

Run from the repository root:
    HF_HOME=.model-cache .venv/bin/python tools/polarity_probe.py
"""

from __future__ import annotations

